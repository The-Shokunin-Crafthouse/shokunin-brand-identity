#!/usr/bin/env node
/**
 * scds-component: the component lookup for agents (ADR-165 decision 3, WQ-142).
 *
 * The docs are the single source: each component's header docblock in
 * src/components/<Name>/<Name>.jsx and its <Name>.tokens.md. This script only
 * reads them; it writes nothing except with --write-index.
 *
 *   node scripts/scds-component.mjs                 index: one line per component
 *   node scripts/scds-component.mjs <Name>          purpose, props, sections
 *   node scripts/scds-component.mjs <Name> props    props with defaults
 *   node scripts/scds-component.mjs <Name> doc      the whole header docblock
 *   node scripts/scds-component.mjs <Name> tokens   token headings of .tokens.md
 *   node scripts/scds-component.mjs <Name> tokens <heading words>   one token section
 *   node scripts/scds-component.mjs --write-index   regenerate src/components/AGENT-INDEX.md
 *   node scripts/scds-component.mjs --check         exit 1 when AGENT-INDEX.md drifts
 *
 * Output stays short on purpose: a long field prints its first sentence and
 * names the call that prints it whole.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'src/components');
const INDEX = path.join(DIR, 'AGENT-INDEX.md');
const MAX = 150;

const names = () =>
  fs.readdirSync(DIR, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort();

const read = (f) => (fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '');
const src = (n) => {
  for (const ext of ['jsx', 'tsx', 'js']) {
    const t = read(path.join(DIR, n, `${n}.${ext}`));
    if (t) return t;
  }
  return '';
};

function docblock(text) {
  const m = text.match(/^\s*\/\*\*([\s\S]*?)\*\//);
  if (!m) return '';
  return m[1].split('\n').map((l) => l.replace(/^\s*\* ?/, '')).join('\n').trim();
}

function firstSentence(block, name) {
  const body = block.replace(new RegExp(`^${name}\\s*[—-]\\s*`), '').replace(/\s*\(\d{4}-\d{2}-\d{2}[^)]*\)/g, '');
  const paras = body.split(/\n\s*\n/).map((x) => x.replace(/\s+/g, ' ').trim()).filter(Boolean);
  const first = (para) => (para.match(/^.*?[.:](?=\s+[A-Z]|$)/) || [para])[0].trim();
  let out = first(paras[0] || '');
  // A spec-ref line ("3.6 · 4 sizes, image.") names variants, not purpose: add the next paragraph.
  if (/^(?:[\d.]+|NEW) ·/.test(paras[0] || '') && paras[1]) out += ' ' + first(paras[1]);
  return out;
}

function clip(s, n = MAX) {
  return s.length <= n ? s : s.slice(0, n - 1).trimEnd() + '…';
}

function props(text, name) {
  const re = new RegExp(`export\\s+(?:default\\s+)?(?:function\\s+${name}|const\\s+${name}\\s*=\\s*(?:forwardRef\\()?\\(?)\\s*\\(?\\s*\\{([\\s\\S]*?)\\}\\s*(?:,\\s*\\w+\\s*)?\\)`);
  const m = text.match(re);
  if (!m) return [];
  const out = [];
  let depth = 0, cur = '';
  for (const ch of m[1]) {
    if ('([{'.includes(ch)) depth++;
    if (')]}'.includes(ch)) depth--;
    if (ch === ',' && depth === 0) { out.push(cur); cur = ''; } else cur += ch;
  }
  out.push(cur);
  return out
    .map((p) => p.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').trim())
    .filter((p) => p && p !== '...rest' && !p.startsWith('...'))
    .map((p) => p.replace(/\s*=\s*/, ' = '));
}

function tokenSections(name) {
  const t = read(path.join(DIR, name, `${name}.tokens.md`));
  const parts = t.split(/^##\s+/m).slice(1);
  return parts.map((p) => {
    const [head, ...rest] = p.split('\n');
    return { head: head.trim(), body: rest.join('\n').trim() };
  });
}

function summary(n) {
  const block = docblock(src(n));
  return { block, purpose: block ? firstSentence(block, n) : '(no header doc)', props: props(src(n), n) };
}

function indexLines() {
  return names().map((n) => {
    const { purpose, props: ps } = summary(n);
    const keys = ps.map((p) => p.split(' ')[0].replace(/[:=].*$/, '')).filter((k) => !['children', 'className'].includes(k));
    return `- **${n}**: ${clip(purpose.replace(new RegExp(`^${n}\\s*[—-]\\s*`), ''), 110)} Props: ${keys.join(', ') || 'none'}.`;
  });
}

function indexMd() {
  return [
    '# SCDS component index',
    '',
    'GENERATED by `node scripts/scds-component.mjs --write-index` from each component header docblock. Do not edit; `--check` fails on drift.',
    'Before hand-building a button, field, toggle, tooltip, toast, avatar, card, pill, skeleton, loader or icon, find it here.',
    'Import from `src/components/<Name>/<Name>.jsx`. One component: `node scripts/scds-component.mjs <Name>`. A section: add `props`, `doc` or `tokens`.',
    '',
    ...indexLines(),
    '',
  ].join('\n');
}

const [a, b, ...rest] = process.argv.slice(2);

if (a === '--write-index') {
  fs.writeFileSync(INDEX, indexMd());
  console.log(`wrote ${path.relative(ROOT, INDEX)}`);
} else if (a === '--check') {
  if (read(INDEX) !== indexMd()) {
    console.error('AGENT-INDEX.md drifts from the component docblocks. Run: node scripts/scds-component.mjs --write-index');
    process.exit(1);
  }
  console.log('AGENT-INDEX.md matches the component docblocks.');
} else if (!a) {
  console.log(indexLines().join('\n'));
} else {
  const n = names().find((x) => x.toLowerCase() === a.toLowerCase());
  if (!n) {
    console.error(`No component "${a}". Known: ${names().join(', ')}`);
    process.exit(1);
  }
  const s = summary(n);
  if (!b) {
    console.log(`${n}: ${clip(s.purpose)}`);
    console.log(`import: src/components/${n}/${n}.jsx`);
    console.log(`props: ${s.props.map((p) => p.split(/\s*=\s*/)[0]).join(', ') || 'none'}`);
    console.log(`more: props (defaults) | doc (whole docblock) | tokens [heading] (${tokenSections(n).length} sections)`);
  } else if (b === 'props') {
    console.log(s.props.join('\n') || 'none');
  } else if (b === 'doc') {
    console.log(s.block || '(no header doc)');
  } else if (b === 'tokens') {
    const secs = tokenSections(n);
    if (!rest.length) {
      console.log(secs.map((x) => `- ${x.head}`).join('\n') || '(no tokens file)');
      console.log(`one section: tokens ${n} <heading words>`);
    } else {
      const q = rest.join(' ').toLowerCase();
      const hit = secs.find((x) => x.head.toLowerCase().includes(q));
      console.log(hit ? `## ${hit.head}\n${hit.body}` : `No section matching "${q}". Run: tokens ${n}`);
    }
  } else {
    console.error('Section must be props, doc or tokens.');
    process.exit(1);
  }
}
